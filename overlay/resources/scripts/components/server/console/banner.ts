const pixels = LOGO_ROWS.map((row) => Array.from(row, (digit) => parseInt(digit, 16)));
const dotBits = [[1, 8], [2, 16], [4, 32], [64, 128]];

export function consoleBanner(cols: number, rows = 24, cellAspect = 2): string {
    const aspect = LOGO_WIDTH / LOGO_ROWS.length;
    // Match the measured terminal cell proportions so the eagle is not stretched.
    const height = Math.max(1, Math.floor(Math.min(26, rows - 3, Math.max(1, cols - 4) / (cellAspect * aspect))));
    const width = Math.max(1, Math.min(cols, Math.round(height * cellAspect * aspect)));
    const padding = ' '.repeat(Math.max(0, Math.floor((cols - width) / 2)));
    const result: string[] = [];
    for (let y = 0; y < height; y++) {
        let line = '';
        for (let x = 0; x < width; x++) {
            let bits = 0;
            for (let dy = 0; dy < 4; dy++) {
                const sy = Math.min(LOGO_ROWS.length - 1, Math.floor((y * 4 + dy + 0.5) * LOGO_ROWS.length / (height * 4)));
                for (let dx = 0; dx < 2; dx++) {
                    const sx = Math.min(LOGO_WIDTH - 1, Math.floor((x * 2 + dx + 0.5) * LOGO_WIDTH / (width * 2)));
                    if (pixels[sy][sx >> 2] & (1 << (3 - (sx % 4)))) bits |= dotBits[dy][dx];
                }
            }
            line += bits ? String.fromCharCode(0x2800 + bits) : ' ';
        }
        result.push(padding + line.trimEnd());
    }
    return ['', ...result, ''].join('\r\n');
}
